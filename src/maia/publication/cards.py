class ModelHub(Protocol):
    """The slice of ``huggingface_hub.HfApi`` used here. Blocked-by-resource."""

    def create_repo(self, repo_id: str, *, repo_type: str, private: bool, exist_ok: bool) -> object:
        """Create (or accept the existence of) a repo."""

    def upload_folder(
        self, *, repo_id: str, folder_path: str, repo_type: str, commit_message: str
    ) -> object:
        """Commit a local folder."""


class NotPublishableError(RuntimeError):
    """Raised when publication is attempted before the M6.01 gate passes."""


@dataclass(frozen=True)
class CardFacts:
    """What a card states, gathered from the artifacts that produced it."""

    examples: int
    corpus_documents: int
    sources: tuple[Source, ...]
    matrix: Matrix | None = None
    base_model: str = "google/gemma-4-12b-it"
    candidate: str = "cand1"
    andbench_url: str = "https://github.com/ericrisco/andbench"


def _data_prose(facts: CardFacts, language: Language) -> str:
    """The data paragraph, which is the one that carries numbers."""
    if language is Language.CA:
        return (
            f"{facts.examples:,} exemples d'instrucció en català, generats a partir "
            f"de {facts.corpus_documents:,} documents d'un corpus andorrà, i sempre "
            "citant-los."
        )
    return (
        f"{facts.examples:,} Catalan instruction examples, generated from "
        f"{facts.corpus_documents:,} documents of an Andorran corpus, always citing "
        "them."
    )


def _evaluation_prose(facts: CardFacts, language: Language) -> str:
    """The evaluation paragraph. MAIA keeps no benchmark of its own (D-0032)."""
    if language is Language.CA:
        return f"Avaluat amb [AndBench]({facts.andbench_url}), no amb un benchmark propi."
    return f"Evaluated with [AndBench]({facts.andbench_url}), not with an in-house benchmark."


def _language_section(facts: CardFacts, language: Language) -> list[str]:
    """One language's half of the model card. Both halves carry the same sections."""
    heads = HEADINGS[language]
    prose = PROSE[language]
    lines = [f"## {'Català' if language is Language.CA else 'English'}", ""]
    for key, text in (
        ("motivation", prose["motivation"]),
        ("data", _data_prose(facts, language)),
        ("method", prose["method"]),
        ("evaluation", _evaluation_prose(facts, language)),
    ):
        lines += [f"### {heads[key]}", "", text, ""]
    if facts.matrix is not None:
        lines += [render_matrix(facts.matrix), ""]
    else:
        lines += [prose["no_matrix"], ""]
    lines += [f"### {heads['limitations']}", ""]
    lines += [f"- {text}" for text in LIMITATIONS[language].values()]
    lines += [
        "",
        f"### {heads['licence']}",
        "",
        f"Model: **{MODEL_LICENSE}**. Dataset: **{DATASET_LICENSE}**.",
        "",
    ]
    return lines


def model_card(facts: CardFacts) -> str:
    """The bilingual model card."""
    front = [
        "---",
        f"license: {MODEL_LICENSE}",
        "language:",
        "  - ca",
        "base_model:",
        f"  - {facts.base_model}",
        "pipeline_tag: text-generation",
        "tags:",
        "  - andorra",
        "  - catalan",
        "  - qlora",
        "---",
        "",
        "# MAIA — Model Andorrà d'Intel·ligència Artificial",
        "",
    ]
    body: list[str] = []
    for language in Language:
        body += _language_section(facts, language)
    return "\n".join([*front, *body])


def dataset_card(facts: CardFacts) -> str:
    """The dataset card, with the per-source attribution the licence requires."""
    lines = [
        "---",
        f"license: {DATASET_LICENSE}",
        "language:",
        "  - ca",
        "task_categories:",
        "  - text-generation",
        "  - question-answering",
        "---",
        "",
        "# andorra-instruct-ca",
        "",
        f"{facts.examples:,} Catalan instruction examples about Andorra, each citing "
        "the corpus passages it was generated from (`grounding_ids`).",
        "",
        "## Limitations",
        "",
    ]
    lines += [f"- {text}" for text in LIMITATIONS[Language.EN].values()]
    lines += ["", attribution_section(facts.sources), ""]
    return "\n".join(lines)


def missing_sections(card: str, *, language: Language | None = None) -> list[str]:
    """Required sections a card does not have.

    Checked **per language**, because that is where the real failure lives: a card can
    have every section somewhere and still drop the limitations from its English half.
    """
    languages = [language] if language is not None else list(Language)
    lowered = card.lower()
    return [
        f"{lang.value}: {key}"
        for lang in languages
        for key in REQUIRED_SECTIONS
        if HEADINGS[lang][key].lower() not in lowered
    ]


def missing_limitations(card: str, *, language: Language | None = None) -> list[str]:
    """Required limitations a card does not state."""
    languages = [language] if language is not None else list(Language)
    lowered = card.lower()
    return [
        f"{lang.value}: {name}"
        for lang in languages
        for name, marker in MARKERS[lang].items()
        if marker.lower() not in lowered
    ]


@dataclass
class PublicationReport:
    """What M6.04 published, and what it refused to."""

    repos: list[str] = field(default_factory=list)
    card_problems: list[str] = field(default_factory=list)
    blocked_by: str = ""

    @property
    def passed(self) -> bool:
        """Whether every repo went out with a complete card."""
        return bool(self.repos) and not self.card_problems and not self.blocked_by


def check_cards(model: str, dataset: str) -> list[str]:
    """Everything wrong with the two cards, as one list."""
    problems = [f"model card missing {item}" for item in missing_sections(model)]
    problems += [f"model card missing limitation {item}" for item in missing_limitations(model)]
    problems += [
        f"dataset card missing limitation {item}"
        for item in missing_limitations(dataset, language=Language.EN)
    ]
    if DATASET_LICENSE not in dataset.lower():
        problems.append("dataset card missing the dataset licence")
    return problems


def publish(
    facts: CardFacts,
    compliance: ComplianceReport,
    hub: ModelHub,
    staging: Mapping[str, Path],
    *,
    private: bool = True,
) -> PublicationReport:
    """Publish the model, GGUF and dataset repos.

    Raises:
        NotPublishableError: if the M6.01 gate has not passed, or the cards are
            incomplete. The ordering — check, then publish — is the only thing that
            makes that gate a gate, so it is enforced here rather than written down as
            a step someone should remember.
    """
    report = PublicationReport()
    if not compliance.passed:
        report.blocked_by = (
            f"the M6.01 legal gate has not passed ({len(compliance.blocking)} blocking finding(s))"
        )
        raise NotPublishableError(
            report.blocked_by + "; publication is gated on it, because a check that "
            "runs after the upload is not a gate"
        )

    model = model_card(facts)
    dataset = dataset_card(facts)
    report.card_problems = check_cards(model, dataset)
    if report.card_problems:
        raise NotPublishableError(
            "the cards are incomplete, and a card is the only part of this project "
            "most people will read:\n"
            + "\n".join(f"  - {problem}" for problem in report.card_problems)
        )

    for repo_id, folder in staging.items():
        repo_type = "dataset" if repo_id == DATASET_REPO else "model"
        card = dataset if repo_type == "dataset" else model
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "README.md").write_text(card, encoding="utf-8")
        hub.create_repo(repo_id, repo_type=repo_type, private=private, exist_ok=True)
        hub.upload_folder(
            repo_id=repo_id,
            folder_path=str(folder),
            repo_type=repo_type,
            commit_message=f"MAIA {facts.candidate}: {facts.examples:,} examples",
        )
        report.repos.append(repo_id)
    return report


def render(report: PublicationReport) -> str:
    """Human-readable summary of a publication run."""
    lines = ["✓ published" if report.passed else "✗ not published"]
    lines += [f"  {repo}" for repo in report.repos]
    if report.blocked_by:
        lines.append(f"  blocked: {report.blocked_by}")
    lines += [f"  ✗ {problem}" for problem in report.card_problems]
    if report.passed:
        lines.append(
            "  the PO validates DoD-F6; this only says the repos went out with complete cards"
        )
    return "\n".join(lines)


def expected_repos() -> tuple[str, str, str]:
    """The three repos the plan names."""
    return (MODEL_REPO, GGUF_REPO, DATASET_REPO)
