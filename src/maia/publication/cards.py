"""Model and dataset cards, and the publication gate — PLAN M6.02-M6.04.

*"Bilingual (ca/en) model card: motivation, data + method, the F4 4-config matrix
table, limitations (synthetic, no oral dialect, no legal advice), licenses (model
Apache 2.0; dataset CC-BY-4.0 with per-source attribution)."*

A card is the only part of this project most people will ever read, which makes it
the one artifact where an omission is not a documentation debt but a
misrepresentation. So the required sections are a **checked list**, not a template
someone fills in.

**Limitations are required, and each names a real constraint from the build.**
*Synthetic* (a frontier model wrote the answers, and only a sample was reviewed by
hand), *no oral dialect* (M1.13's spoken subcorpora were used for register only,
never to clone a voice — D7), and *not legal advice* (the model is trained on
consolidated Andorran law, which is exactly what makes someone ask). A card missing
any of them describes a model that does not exist.

**Bilingual means both languages carry the same sections.** A Catalan card whose
English half quietly drops the limitations is worse than a monolingual one: it
presents a complete document to a reader who cannot check. So
:func:`missing_sections` and :func:`missing_limitations` check **per language**.

**The evaluation table is the F4 matrix, rendered, not retyped.** M4.05 already
produces it; a hand-copied table is a second source of truth that drifts, and this
one drifts *towards* flattering numbers.

**The upload is gated on M6.01.** :func:`publish` refuses to run when the legal gate
has not passed, because the ordering — check, then publish — is the only thing that
makes the gate a gate.
"""

