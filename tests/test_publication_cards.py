def matrix() -> object:
    return from_results(
        {
            Config.BASE: [TrackResult(track=Track.OBERT, score=0.50, items=100)],
            Config.BASE_RAG: [TrackResult(track=Track.OBERT, score=0.70, items=100)],
            Config.TUNED: [TrackResult(track=Track.OBERT, score=0.72, items=100)],
            Config.TUNED_RAG: [TrackResult(track=Track.OBERT, score=0.92, items=100)],
        }
    )


def facts(**overrides: object) -> CardFacts:
    base = {
        "examples": 12_000,
        "corpus_documents": 8_500,
        "sources": (Source.JURIDIC, Source.VIQUIPEDIA),
        "matrix": matrix(),
    }
    return CardFacts(**{**base, **overrides})  # type: ignore[arg-type]


def clean_compliance() -> ComplianceReport:
    return ComplianceReport(examples=12_000, corpus_supplied=True, card_checked=True)


@dataclass
class FakeHub:
    created: list[tuple[str, str, bool]] = field(default_factory=list)
    uploaded: list[tuple[str, str]] = field(default_factory=list)

    def create_repo(self, repo_id: str, *, repo_type: str, private: bool, exist_ok: bool) -> object:
        self.created.append((repo_id, repo_type, private))
        return None

    def upload_folder(
        self, *, repo_id: str, folder_path: str, repo_type: str, commit_message: str
    ) -> object:
        self.uploaded.append((repo_id, commit_message))
        return None


