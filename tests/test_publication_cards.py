@pytest.mark.unit
def test_publication_requires_the_legal_gate_to_have_passed(tmp_path: Path) -> None:
    """A check that runs after the upload is not a gate."""
    blocked = ComplianceReport(examples=1, corpus_supplied=False, card_checked=False)
    assert not blocked.passed
    with pytest.raises(NotPublishableError, match=r"the M6\.01 legal gate has not passed"):
        publish(facts(), blocked, FakeHub(), {MODEL_REPO: tmp_path / "model"})


@pytest.mark.unit
def test_nothing_is_uploaded_when_the_gate_blocks(tmp_path: Path) -> None:
    hub = FakeHub()
    with pytest.raises(NotPublishableError):
        publish(facts(), ComplianceReport(), hub, {MODEL_REPO: tmp_path / "model"})
    assert hub.uploaded == []
    assert hub.created == []


@pytest.mark.unit
def test_a_clean_gate_publishes_all_three_repos(tmp_path: Path) -> None:
    hub = FakeHub()
    staging = {repo: tmp_path / repo.split("/")[-1] for repo in expected_repos()}
    report = publish(facts(), clean_compliance(), hub, staging)
    assert report.passed
    assert sorted(report.repos) == sorted(expected_repos())
    assert "the PO validates DoD-F6" in render(report)


@pytest.mark.unit
def test_the_dataset_repo_is_created_as_a_dataset(tmp_path: Path) -> None:
    hub = FakeHub()
    staging = {repo: tmp_path / repo.split("/")[-1] for repo in expected_repos()}
    publish(facts(), clean_compliance(), hub, staging)
    kinds = {repo: kind for repo, kind, _ in hub.created}
    assert kinds[DATASET_REPO] == "dataset"
    assert kinds[MODEL_REPO] == "model"
    assert kinds[GGUF_REPO] == "model"


@pytest.mark.unit
def test_each_repo_gets_the_right_card(tmp_path: Path) -> None:
    staging = {repo: tmp_path / repo.split("/")[-1] for repo in expected_repos()}
    publish(facts(), clean_compliance(), FakeHub(), staging)
    model_readme = (staging[MODEL_REPO] / "README.md").read_text(encoding="utf-8")
    dataset_readme = (staging[DATASET_REPO] / "README.md").read_text(encoding="utf-8")
    assert "MAIA — Model Andorrà" in model_readme
    assert "andorra-instruct-ca" in dataset_readme
    assert "## Attributions" in dataset_readme


