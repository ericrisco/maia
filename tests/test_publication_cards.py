    """A card is the only part of this project most people will read."""
    monkeypatch.setattr("maia.publication.cards.model_card", lambda facts_: "# MAIA\n")
    hub = FakeHub()
    with pytest.raises(NotPublishableError, match="the cards are incomplete"):
        publish(facts(), clean_compliance(), hub, {MODEL_REPO: tmp_path / "m"})
    assert hub.uploaded == []


