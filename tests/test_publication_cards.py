@pytest.mark.unit
def test_a_card_missing_the_english_limitations_is_caught() -> None:
    """Worse than a monolingual card: it presents a complete document to a reader who
    cannot check."""
    card = model_card(facts())
    for text in LIMITATIONS_EN:
        card = card.replace(text, "")
    problems = missing_limitations(card, language=Language.EN)
    assert len(problems) == 3
    assert missing_limitations(card, language=Language.CA) == []


